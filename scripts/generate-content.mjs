// Generates typed content modules straight from the official source files so
// that no testimonial, attribution or logo path is ever retyped by hand.
// Run from project root:  node scripts/generate-content.mjs
import fs from "fs";
const R = "research/";
fs.mkdirSync("src/content/generated", { recursive: true });
const banner = (src) => `// AUTO-GENERATED by scripts/generate-content.mjs — do not edit by hand.\n// Source: ${src}\n\n`;

// 1) Logo ---------------------------------------------------------------
const svg = fs.readFileSync(R + "logo.svg", "utf8");
const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
const inner = [...svg.matchAll(/<(path|rect)\b[^>]*\/>/g)]
  .map((m) => m[0].replace(/\s*style="[^"]*"/g, "").replace(/\s+/g, " "))
  .join("");
fs.writeFileSync("src/content/generated/logo.ts",
  banner("https://bluetomatomarketing.com/assets/img/blue-tomato.svg (fills removed so the mark inherits currentColor)") +
  `export const LOGO_VIEWBOX = ${JSON.stringify(viewBox)};\nexport const LOGO_MARKUP = ${JSON.stringify(inner)};\n`);

// 2) Testimonials -------------------------------------------------------
const home = fs.readFileSync(R + "home.html", "utf8");
const decode = (v) => v.replace(/&rsquo;/g, "\u2019").replace(/&lsquo;/g, "\u2018").replace(/&ldquo;/g, "\u201C").replace(/&rdquo;/g, "\u201D")
  .replace(/&mdash;/g, "\u2014").replace(/&ndash;/g, "\u2013").replace(/&hellip;/g, "\u2026").replace(/&amp;/g, "&").replace(/&#0?39;/g, "'").replace(/&nbsp;/g, " ");
const t = [...home.matchAll(/<blockquote class="testimonial">([\s\S]*?)<\/blockquote>/g)].map(([, block]) => {
  const foot = block.match(/<footer>([\s\S]*?)<\/footer>/)[1];
  const body = block.slice(0, block.indexOf("<footer>"));
  const quote = body.split(/<\/p>|<br\s*\/?>\s*<br\s*\/?>/).map((p) => decode(p.replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim())).filter(Boolean);
  const m = foot.match(/^\s*([\s\S]*?)\s+-\s+<i>([\s\S]*?)<\/i>\s*<br>\s*([\s\S]*?)\s*$/);
  return { quote, name: decode(m[1].trim()), title: decode(m[2].trim()), company: decode(m[3].trim()) };
});
const featured = ["Michael Arnold", "Eric Wolff", "Mark Villella", "John Ifft", "Jamie Rogers"];
const rows = t.map((x) => ({ ...x, featured: featured.includes(x.name) }));
fs.writeFileSync("src/content/generated/testimonials.ts",
  banner("https://bluetomatomarketing.com/ — .client-testimonials (all 26 quotations, verbatim, original order)") +
  `export type Testimonial = { quote: string[]; name: string; title: string; company: string; featured: boolean };\n\n` +
  `export const FEATURED_ORDER = ${JSON.stringify(featured)};\n\n` +
  `export const testimonials: Testimonial[] = ${JSON.stringify(rows, null, 2)};\n`);

// 3) Identity work (logo portfolio) ------------------------------------
const labels = {
  "virtualmgr": "VirtualMGR", "clward": "CLWARD", "neurointerventions": "NeuroInterventions", "geonetix": "GeoNetix",
  "m3-creative-media": "M3 Creative Media", "flat-iron-energy-partners": "Flat Iron Energy Partners", "pro-flo": "PRO FLO",
  "esquire-legal-services": "Esquire Legal Services", "curis": "Curis", "spiralgen": "SpiralGen", "head-right": "Head Right",
  "vista-energy-resources": "Vista Energy Resources", "brighton-resources": "Brighton Resources Inc.",
  "carmell-therapeutics": "Carmell Therapeutics", "wpts-radio": "WPTS Radio", "firstinsight": "FirstInsight",
};
const man = JSON.parse(fs.readFileSync(R + "manifest.json", "utf8")).filter((m) => m.file.includes("/logos/") && !m.file.includes("/mono/"));
const out = {};
for (const m of man) {
  const key = m.file.split("/").pop().replace(".webp", "");
  out[key] = { src: m.file.replace("public/", ""), width: m.w, height: m.h, alt: `${labels[key]} logo`, name: labels[key],
    origin: "https://bluetomatomarketing.com/uploads/projects/800-800/fit/" + m.src };
}
fs.writeFileSync("src/content/generated/identity.ts",
  banner("https://bluetomatomarketing.com/portfolio/logos — identity work tiles") +
  `export type IdentityLogo = { src: string; width: number; height: number; alt: string; name: string; origin: string };\n\n` +
  `export const identity: Record<string, IdentityLogo> = ${JSON.stringify(out, null, 2)};\n`);
console.log("generated:", fs.readdirSync("src/content/generated").join(", "), "| logos:", Object.keys(out).length, "| logo markup bytes:", inner.length);
